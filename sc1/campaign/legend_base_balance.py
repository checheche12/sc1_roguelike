"""QA46: reduce large baseline bonuses while retaining legendary mechanics."""
REVISION = 2026102046
BASE_BONUSES = {54: 100, 60: 150, 105: 100, 141: 150, 194: 75}
SCALARS = {
    'irradiate_damage_multiplier': 2,
    'organic_lockdown_duration_multiplier': 2,
    'scourge_health_multiplier': 2,
    'plague_damage_multiplier': 2,
    'devourer_ground_damage_percent': 200,
    'storm_radius_bonus_percent': 100,
}


def decorate(catalog):
    by = {x['effect_ordinal']: x for x in catalog['talents'] if x.get('rework_revision') == 5}
    for ordinal, bonus in BASE_BONUSES.items():
        item = by[ordinal]
        old = item['effect']['base_bonus_percent']
        item['description'] = item['description'].replace(f'일반 공격 피해 +{old}%', f'일반 공격 피해 +{bonus}%')
        item['effect'].update(base_bonus_percent=bonus, qa_revision=REVISION)
    by[54]['description'] = (
        '일반 공격 피해 +100%. 이동 중에도 사격합니다. 이동 중 피해 +100% 추가(총300%). 정지 시 총200%.')
    by[105]['effect']['projectile_damage_percent'] = 200
    changes = {
        61: ('피해 3배', '피해 2배', {'damage_multiplier': SCALARS['irradiate_damage_multiplier']}),
        63: ('지속 시간이 최대 4배', '지속 시간이 최대 2배', {'organic_duration_multiplier': SCALARS['organic_lockdown_duration_multiplier']}),
        96: ('최대 체력3배', '최대 체력2배', {'health_multiplier': SCALARS['scourge_health_multiplier']}),
        102: ('체력 피해가 4배', '체력 피해가 2배', {'damage_multiplier': SCALARS['plague_damage_multiplier']}),
        106: ('지상 피해400%', '지상 피해200%', {'ground_damage_percent': SCALARS['devourer_ground_damage_percent']}),
        144: ('반경 +200%', '반경 +100%', {'radius_bonus_percent': SCALARS['storm_radius_bonus_percent']}),
    }
    for ordinal, (old, new, values) in changes.items():
        item = by[ordinal]
        assert old in item['description'], (ordinal, item['description'])
        item['description'] = item['description'].replace(old, new)
        item['effect'].update(values, qa_revision=2026102269 if ordinal==96 else REVISION)
    by[54]['description']+=' 공격 유형이 일반형으로 바뀝니다.'
    by[54]['effect'].update(qa_revision=2026102261,weapon_damage_type=3)
    by[141]['description']+=' 스캐럽 미네랄 비용0.'
    by[141]['effect'].update(qa_revision=2026102384,scarab_mineral_cost=0,reaver_move_speed_bonus_percent=100,reaver_move_speed_multiplier=2,reaver_move_speed_units=[81,83],scarab_production_speed_bonus_percent=50,scarab_production_speed_multiplier=1.5,scarab_build_time_numerator=2,scarab_build_time_denominator=3)
    catalog['legend_base_balance_revision'] = REVISION
    return catalog


def generate_header(catalog, root):
    lines = ['#pragma once', '// Generated by campaign/legend_base_balance.py.', 'namespace legend_base_balance {']
    lines.extend(f'inline constexpr unsigned {key}={value}u;' for key, value in SCALARS.items())
    lines.append('}')
    path = root / 'sc1/native_campaign/plugin/include/legend_base_balance.generated.h'
    path.write_text('\n'.join(lines) + '\n', encoding='utf8')
    return path
